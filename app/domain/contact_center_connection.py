"""An organisation's own contact-center connection (ADR 0032 points 9–11, ADR 0042 step 6b-2).

Each organisation may connect its own tenant of a contact-center platform: the API host, the
OAuth client and, generated by the server, the webhook secret its events are signed with. The
secrets are sealed and write-only (ADR 0008); the portal sees ``OrganisationConnection`` only.
Every change is authorised by ``integrations.manage`` for that organisation and audited by
field name, never by value. An organisation without a connection uses the installation's for
one minor (point 11, ADR 0116).

    view(org)   ─► OrganisationConnection | None
    save(org)   ─► audit ─► sealed record ─► register the address  (a blank secret keeps one;
                                              not when only the allowed networks changed)
    rotate(org) ─► audit ─► new webhook secret ─► register again     (CC-4d)
    set_inbound ─► audit ─► the one field of the sealed record  (the pause, ADR 0124 point 9;
                            no secret, no registration)
    remove(org) ─► audit ─► record deleted

Registering tells the platform to send the organisation's events to its own address, signed
with its current secret; its outcome is audited and shown to the admin, never a reason to undo
the change.
"""

from collections.abc import Callable
from dataclasses import dataclass

from app.domain.admin import AdminService, record_change
from app.domain.authorization import Permission, Principal, scope_for
from app.domain.contact_center import (
    CONNECTION_FIELD,
    ConnectionChange,
    ContactCenterKind,
    OrganisationConnection,
    Registration,
)
from app.domain.errors import DomainError, ErrorCode
from app.domain.networks import NetworkList
from app.domain.ports import Clock, ConnectionRegistrar, ContactCenterConnections, UnitOfWork
from app.domain.scheduling import is_slug

PERMISSION = Permission.INTEGRATIONS_MANAGE
AUDIT_KEY = "contact_center_connection"
NETWORKS_AUDIT = "allowed_networks"
"""The audit names the field that changed, never the networks (as it does for the secrets)."""
PAUSE_AUDIT = {True: "resume", False: "pause"}
"""The audit action of setting the pause (``contact_center_connection.pause`` or ``.resume``),
written only when the state changes; never a value."""


def _only_networks_changed(stored: OrganisationConnection, change: ConnectionChange) -> bool:
    """Whether a saved change differs from the stored connection in its allowed networks only.

    Nothing the registration at the platform depends on changed then: the kind, the API host,
    the client and the secrets are as they were. Whether the webhook secret exists is asked
    separately (``save``): a record without one is not left alone.
    """
    return (stored.kind, stored.api_base_url, stored.client_id) == (
        change.kind,
        change.api_base_url,
        change.client_id,
    ) and not change.secrets_sent


@dataclass(frozen=True)
class WebhookTarget:
    """Where an organisation's own webhook address stands: found, or missing.

    Attributes:
        organisation_id: The organisation's id; ``None`` when the address does not exist.
        secret: The webhook secret its events are signed with; ``None`` when missing.
        organisation: The organisation's slug, set only when that organisation exists (and has
            no connection); ``None`` when it does not, so a slug a caller made up is never
            handed on.
        allowed_networks: The connection's own list of source networks (ADR 0124 point 3);
            empty: the installation's default applies; unreadable: no call is accepted.
        inbound_enabled: Whether the address handles its events (ADR 0124 point 9); off: a
            verified event is dropped.
    """

    organisation_id: int | None = None
    secret: str | None = None
    organisation: str | None = None
    allowed_networks: NetworkList = NetworkList()
    inbound_enabled: bool = True

    @property
    def found(self) -> bool:
        """Whether the address exists: an organisation connected to the platform, with a secret."""
        return self.organisation_id is not None and self.secret is not None


class ContactCenterConnectionService:
    """Reads and changes an organisation's contact-center connection.

    Args:
        uow: Opens database transactions (organisation lookup and audit).
        clock: Current time.
        admin: Decides permissions.
        connections: The sealed connections; ``None`` without a settings key, when nothing can
            be sealed.
        registrar: Returns what registers the address at the platform (the integrations are
            rebuilt when the settings change); returning ``None``: not registered.
    """

    def __init__(
        self,
        uow: UnitOfWork,
        clock: Clock,
        admin: AdminService,
        connections: ContactCenterConnections | None,
        registrar: Callable[[], ConnectionRegistrar | None],
    ) -> None:
        """Store the collaborators."""
        self._registrar = registrar
        self._uow = uow
        self._clock = clock
        self._admin = admin
        self._connections = connections

    @property
    def available(self) -> bool:
        """Whether connections can be kept at all (a settings key is configured)."""
        return self._connections is not None

    async def view(self, principal: Principal, organisation: str) -> OrganisationConnection | None:
        """Return the organisation's connection without secrets, or ``None``.

        Raises:
            DomainError: ``not_permitted`` or ``organisation_not_found``.
        """
        organisation_id = await self._authorize(principal, organisation)
        if self._connections is None:
            return None
        return await self._connections.get(organisation_id)

    async def paused_connections(self, principal: Principal) -> dict[str, ContactCenterKind]:
        """Return the organisations whose webhook address is paused, with their platform.

        For the status screens (ADR 0124 point 9), so that a pause reads as paused and not as a
        healthy or a silent connection. Only organisations the reader may manage integrations
        for; empty without a settings key. One read of the connections for all of them.
        """
        if self._connections is None:
            return {}
        async with self._uow.read() as tx:
            organisations = await tx.list_organisations(
                scope_for(principal, Permission.INTEGRATIONS_MANAGE)
            )
        paused = await self._connections.paused([o.id for o in organisations])
        return {o.slug: paused[o.id] for o in organisations if o.id in paused}

    async def webhook_target(self, slug: str, kind: ContactCenterKind) -> WebhookTarget:
        """Return whether an organisation's own webhook address exists (ADR 0032 point 10).

        It exists when ``slug`` names an organisation that is connected to ``kind`` with a
        webhook secret. No permission is asked: the caller is a platform, authenticated by the
        signature that this secret verifies.

        Args:
            slug: The organisation's slug as it came in the address; any text.
            kind: The platform.

        Returns:
            The organisation's id and secret when the address exists. Otherwise ``found`` is
            false, and ``organisation`` names the slug only when that organisation exists.
        """
        if self._connections is None or not is_slug(slug):
            return WebhookTarget()
        organisation_id = await self._admin.organisation_id(slug)
        if organisation_id is None:
            return WebhookTarget()
        secret = await self._connections.webhook_secret(organisation_id, kind)
        if secret is None:
            return WebhookTarget(organisation=slug)
        shown = await self._connections.get(organisation_id)
        return WebhookTarget(
            organisation_id,
            secret,
            slug,
            shown.allowed_networks if shown else NetworkList(),
            shown.inbound_enabled if shown else True,
        )

    async def save(
        self, principal: Principal, organisation: str, change: ConnectionChange
    ) -> Registration:
        """Store the connection; audited by the names of the fields sent, never their values.

        A change of the allowed networks alone (ADR 0124 point 3) on a connection that has its
        webhook secret is stored and audited, makes no new webhook secret and does not register
        the address again (``Registration.UNTOUCHED``). A record without a secret takes the
        normal path: the secret is made and the address registered.

        Raises:
            DomainError: ``not_permitted``, ``organisation_not_found``, ``integration_not_ready``
                (no settings key), ``invalid_configuration`` naming ``client_secret`` when a
                new connection comes without one.
        """
        organisation_id = await self._authorize(principal, organisation)
        connections = self._ready()
        stored = await connections.get(organisation_id)
        if change.client_secret is None and stored is None:
            raise DomainError(ErrorCode.INVALID_CONFIGURATION, f"{CONNECTION_FIELD}client_secret")
        networks_changed = change.allowed_networks is not None and NetworkList(
            change.allowed_networks
        ) != (stored.allowed_networks if stored else NetworkList())
        sent = [*change.secrets_sent, *([NETWORKS_AUDIT] if networks_changed else [])]
        detail = ",".join([f"{AUDIT_KEY}.save", f"kind:{change.kind.value}", *sent])
        # Asked before the save: the save makes a secret for a record that has none.
        leave_alone = (
            networks_changed
            and stored is not None
            and _only_networks_changed(stored, change)
            and await connections.webhook_secret(organisation_id, stored.kind) is not None
        )
        await self._audit(principal, organisation, detail)
        await connections.save(organisation_id, change, self._clock.now())
        if leave_alone:
            # The subscription depends on the secret, the host and the client, not on who may call.
            return Registration.UNTOUCHED
        return await self._register(principal, organisation_id, organisation)

    async def set_inbound(self, principal: Principal, organisation: str, *, enabled: bool) -> bool:
        """Pause or resume the organisation's webhook address (ADR 0124 point 9).

        The state wanted is given, never toggled, so a stale page that presses the same button
        twice does the same thing twice. Audited by name (``contact_center_connection.pause`` or
        ``.resume``), and only when the state changes. It never makes a secret and never
        registers: the platform keeps its subscription and gets its 204 either way.

        Returns:
            Whether the state changed.

        Raises:
            DomainError: ``not_permitted``, ``organisation_not_found``, ``integration_not_ready``
                (no settings key) and ``invalid_configuration`` naming ``connection`` when the
                organisation has no connection.
        """
        organisation_id = await self._authorize(principal, organisation)
        connections = self._ready()
        stored = await connections.get(organisation_id)
        if stored is None:
            raise DomainError(ErrorCode.INVALID_CONFIGURATION, f"{CONNECTION_FIELD}connection")
        if stored.inbound_enabled == enabled:
            return False
        await self._audit(principal, organisation, f"{AUDIT_KEY}.{PAUSE_AUDIT[enabled]}")
        await connections.set_inbound_enabled(organisation_id, enabled, self._clock.now())
        return True

    async def rotate_webhook_secret(self, principal: Principal, organisation: str) -> Registration:
        """Generate a new webhook secret; the old one stops verifying at once.

        Raises:
            DomainError: as ``save``, and ``invalid_configuration`` naming ``connection`` when
                the organisation has no connection yet.
        """
        organisation_id = await self._authorize(principal, organisation)
        connections = self._ready()
        if await connections.get(organisation_id) is None:
            raise DomainError(ErrorCode.INVALID_CONFIGURATION, f"{CONNECTION_FIELD}connection")
        await self._audit(principal, organisation, f"{AUDIT_KEY}.rotate_webhook_secret")
        await connections.rotate_webhook_secret(organisation_id, self._clock.now())
        return await self._register(principal, organisation_id, organisation)

    async def remove(self, principal: Principal, organisation: str) -> None:
        """Remove the connection; the organisation falls back to the installation's.

        Raises:
            DomainError: as ``save``.
        """
        organisation_id = await self._authorize(principal, organisation)
        connections = self._ready()
        await self._audit(principal, organisation, f"{AUDIT_KEY}.remove")
        await connections.delete(organisation_id)

    async def _register(
        self, principal: Principal, organisation_id: int, organisation: str
    ) -> Registration:
        """Register the organisation's address at its platform and audit the outcome."""
        registrar = self._registrar()
        if registrar is None:
            return Registration.NOT_READY
        outcome = await registrar.register(organisation_id, organisation)
        await self._audit(principal, organisation, f"{AUDIT_KEY}.register,outcome:{outcome.value}")
        return outcome

    def _ready(self) -> ContactCenterConnections:
        """Return the sealed connections, or refuse when no settings key is configured."""
        if self._connections is None:
            raise DomainError(ErrorCode.INTEGRATION_NOT_READY, "settings_key")
        return self._connections

    async def _audit(self, principal: Principal, organisation: str, detail: str) -> None:
        """Record the change first: a change without its event is worse than the reverse."""
        async with self._uow.locked() as tx:
            await record_change(
                tx, self._clock.now(), principal, PERMISSION, organisation, None, detail
            )

    async def _authorize(self, principal: Principal, organisation: str) -> int:
        """Authorise ``integrations.manage`` on the organisation; return its id."""
        return await self._admin.authorize_organisation(principal, PERMISSION, organisation)
