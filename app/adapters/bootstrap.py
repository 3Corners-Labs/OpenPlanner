"""First install: generate the bootstrap keys into a private file (ADR 0042 §9).

``python -m app.cli init`` writes ``SETTINGS_ENCRYPTION_KEY``, ``MANAGEMENT_TOKEN_KEY`` and
``SESSION_SECRET`` to ``secrets/secrets.env`` (mode 0600, directory 0700). It never overwrites
a file: a new settings key makes every stored secret unreadable. Production never generates
keys at start-up; a key on the same volume as the database would undo encryption at rest.
"""

import os
import secrets
from datetime import UTC, datetime
from pathlib import Path

from app.domain.settings_registry import BY_KEY, REGISTRY, SettingClass, SettingSpec, Topic

GENERATED = ("settings_encryption_key", "management_token_key", "session_secret")
"""The keys ``init`` generates; every other bootstrap value comes from the operator."""

KEY_BYTES = 48
"""Random bytes per key (``secrets.token_urlsafe``), as ADR 0042 §9 sets; a fixed rule."""

DEFAULT_PATH = Path("secrets/secrets.env")
"""Where ``init`` writes by default; ``docker-compose.yml`` reads it when present."""


class InitRefusedError(Exception):
    """The target file exists already; nothing was written."""


def write_secrets(path: Path) -> None:
    """Write freshly generated bootstrap keys to ``path``; refuse an existing file.

    Raises:
        InitRefusedError: ``path`` exists.
    """
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    stamp = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        f"# Generated by `python -m app.cli init` on {stamp} (ADR 0042).",
        "# Keep a copy apart from the database backup: without SETTINGS_ENCRYPTION_KEY the",
        "# secrets stored in the database cannot be read. Never commit this file.",
        *(f"{BY_KEY[key].env}={secrets.token_urlsafe(KEY_BYTES)}" for key in GENERATED),
    ]
    try:
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        raise InitRefusedError(str(path)) from None
    with os.fdopen(fd, "w", encoding="utf-8") as out:
        out.write("\n".join(lines) + "\n")


def remaining_variables() -> list[SettingSpec]:
    """Return the class A and B variables the operator still fills in (no development ones)."""
    return [
        spec
        for spec in REGISTRY
        if spec.class_ in (SettingClass.BOOTSTRAP, SettingClass.DEPLOYMENT)
        and spec.key not in GENERATED
        and spec.topic is not Topic.DEVELOPMENT
    ]
